-- 앱 · 기타: 앱 키 · 활동완료 로그 · 도움돼요 로그 · 꿀팁 바구니 · 의견 (설계서 3절 5. 앱 연결)
-- 로그는 app_key_id · activity_id 숫자만 둔다 — FK 없음 · 쌓기만 한다 · 지금은 일반 테이블 (커지면 월별 파티션)

create table member_app_key (
    app_key_id    bigint generated by default as identity primary key,
    app_key       varchar(64) not null,
    app_hash      varchar(64) not null,
    member_id     bigint      references member (member_id),
    linked_at     timestamptz,
    last_used_at  timestamptz,
    created_at    timestamptz not null,
    updated_at    timestamptz not null,
    constraint uk_member_app_key_app_key unique (app_key)
);
create index ix_member_app_key_member on member_app_key (member_id);   -- 회원에 연결된 앱 · 탈퇴 처리

create table app_done_log (
    done_id      bigint generated by default as identity primary key,
    app_key_id   bigint      not null,
    activity_id  bigint      not null,
    done_on      date        not null,
    created_at   timestamptz not null,
    constraint uk_app_done_log_activity_app_day unique (activity_id, app_key_id, done_on)   -- 같은 활동은 하루 한 번 · 활동별로 셀 때도 쓴다
);

create table app_helped_log (
    helped_id    bigint generated by default as identity primary key,
    app_key_id   bigint      not null,
    activity_id  bigint      not null,
    helpful      boolean     not null,
    created_at   timestamptz not null
);
create index ix_app_helped_log_app_activity on app_helped_log (app_key_id, activity_id, created_at);   -- 같은 상태 막기 (그 앱 · 그 활동의 마지막 행)

create table cart (
    cart_id      bigint generated by default as identity primary key,
    member_id    bigint      not null references member (member_id),
    target_type  varchar(20) not null,
    target_id    bigint      not null,
    days         varchar(30),
    sent_at      timestamptz,
    created_at   timestamptz not null,
    updated_at   timestamptz not null,
    constraint uk_cart_member_target unique (member_id, target_type, target_id)   -- 같은 것은 한 번만 담김 · 회원별 조회에도 쓴다
);

create table feedback (
    feedback_id    bigint generated by default as identity primary key,
    member_id      bigint      not null references member (member_id),
    type           varchar(20) not null,
    feedback_text  text        not null,
    lang           varchar(20) not null,
    handled_at     timestamptz,
    created_at     timestamptz not null,
    updated_at     timestamptz not null
);
create index ix_feedback_member on feedback (member_id);   -- 내 의견 · 탈퇴 처리
