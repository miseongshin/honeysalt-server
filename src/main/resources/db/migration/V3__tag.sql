-- 태그: #상황 태그 · 회원 태그 · 글과 회원에 잇는 연결 테이블 · 사용이 차단된 태그 (설계서 3절 2. 태그)
-- 이름만으로 중복을 막는다 — 묶음(tag_group)을 옮기거나 없애도 태그는 한 행 · #상황 태그는 tag_group 이 NULL · lang 은 처음 만든 사람의 언어(기록만)
-- 이름은 50자까지 저장할 수 있다 (작성 시 한국어 · 중국어 · 일본어는 10자, 그 외 언어는 20자 — 검증은 코드에서)
-- 연결 테이블은 PK (대상_id, tag_id) + 역색인 (tag_id, 대상_id) · 날짜 없이 지우고 다시 넣는다
-- 태그를 차단하면 tag 행을 지우고 이름을 tag_blocklist 로 옮긴다 — 연결 행은 on delete cascade 로 같이 지워진다

create table tag (
    tag_id      bigint generated by default as identity primary key,
    tag_group   varchar(20),
    lang        varchar(20),
    name        varchar(50) not null,
    use_count   integer     not null default 0,
    created_at  timestamptz not null,
    updated_at  timestamptz not null,
    constraint uk_tag_name unique (name)
);
create index ix_tag_popular on tag (use_count desc);   -- 많이 찾는 상황

create table member_tag (
    member_id  bigint not null references member (member_id) on delete cascade,   -- 탈퇴하면 고른 태그도 지운다
    tag_id     bigint not null references tag (tag_id) on delete cascade,
    primary key (member_id, tag_id)
);
create index ix_member_tag_tag on member_tag (tag_id, member_id);

create table honey_worry_tag (
    worry_id  bigint not null references honey_worry (worry_id),
    tag_id    bigint not null references tag (tag_id) on delete cascade,
    primary key (worry_id, tag_id)
);
create index ix_honey_worry_tag_tag on honey_worry_tag (tag_id, worry_id);

create table honey_thought_tip_tag (
    thought_tip_id  bigint not null references honey_thought_tip (thought_tip_id),
    tag_id          bigint not null references tag (tag_id) on delete cascade,
    primary key (thought_tip_id, tag_id)
);
create index ix_honey_thought_tip_tag_tag on honey_thought_tip_tag (tag_id, thought_tip_id);

create table honey_schedule_tag (
    schedule_id  bigint not null references honey_schedule (schedule_id),
    tag_id       bigint not null references tag (tag_id) on delete cascade,
    primary key (schedule_id, tag_id)
);
create index ix_honey_schedule_tag_tag on honey_schedule_tag (tag_id, schedule_id);

create table honey_activity_tag (
    activity_id  bigint not null references honey_activity (activity_id),
    tag_id       bigint not null references tag (tag_id) on delete cascade,
    primary key (activity_id, tag_id)
);
create index ix_honey_activity_tag_tag on honey_activity_tag (tag_id, activity_id);

create table tag_blocklist (
    name        varchar(50)  primary key,   -- 차단한 태그 이름 · tag 와 연결하지 않는다
    reason      varchar(200) not null,
    created_at  timestamptz  not null
);
