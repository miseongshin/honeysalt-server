-- 반응: 댓글 · 좋아요 · 신고 (설계서 3절 3. 댓글, 좋아요)
-- 좋아요 · 신고는 대상 종류(target_type) + 대상 번호(target_id) 로 여러 테이블을 가리킨다 — FK 없음
-- 댓글은 한국어 · 중국어 · 일본어는 200자, 그 외 언어는 400자까지 작성할 수 있다 (칸은 500자 — 검증은 코드에서)

create table honey_comment (
    comment_id     bigint generated by default as identity primary key,
    activity_id    bigint       references honey_activity (activity_id),
    schedule_id    bigint       references honey_schedule (schedule_id),
    member_id      bigint       not null references member (member_id),
    comment_text   varchar(500) not null,
    lang           varchar(20)  not null,
    status         varchar(20)  not null,
    hidden_at      timestamptz,
    hidden_reason  varchar(200),
    like_count     integer      not null default 0,
    created_at     timestamptz  not null,
    updated_at     timestamptz  not null,
    constraint ck_honey_comment_one_target check (num_nonnulls(activity_id, schedule_id) = 1)   -- 활동 · 스케줄 둘 중 하나만
);
create index ix_honey_comment_activity on honey_comment (activity_id, created_at);   -- 활동 상세
create index ix_honey_comment_schedule on honey_comment (schedule_id, created_at);   -- 스케줄 상세
create index ix_honey_comment_member   on honey_comment (member_id);                 -- 내 댓글 · 탈퇴 처리

create table honey_like (
    like_id      bigint generated by default as identity primary key,
    member_id    bigint      not null references member (member_id),
    target_type  varchar(20) not null,
    target_id    bigint      not null,
    created_at   timestamptz not null,
    constraint uk_honey_like_member_target unique (member_id, target_type, target_id)
);
create index ix_honey_like_target  on honey_like (target_type, target_id);   -- 좋아요 수 다시 세기 · 잠금 확인

create table honey_complaint (
    complaint_id    bigint generated by default as identity primary key,
    member_id       bigint      not null references member (member_id),
    target_type     varchar(20) not null,
    target_id       bigint      not null,
    reason          varchar(20) not null,
    complaint_text  text,
    handled_at      timestamptz,
    created_at      timestamptz not null,
    constraint uk_honey_complaint_member_target unique (member_id, target_type, target_id)
);
create index ix_honey_complaint_target  on honey_complaint (target_type, target_id);   -- 같은 대상의 신고 수(세 번째 신고 시 관리자 이메일 발송)
create index ix_honey_complaint_waiting on honey_complaint (created_at) where handled_at is null;   -- 미처리 신고 목록
