-- 꿀방울 주요 기능: 고민 · 생각꿀팁 · 링크 · 활동 · 활동꿀팁 · 스케줄 (설계서 3절 1. 주요기능)
-- 글 입력 칸은 500자까지 저장할 수 있다 (작성 시 한국어 · 중국어 · 일본어는 200자, 그 외 언어는 400자 — 검증은 코드에서) · 시각은 timestamptz (UTC)
-- 미션은 테이블 없이 번호(1~7, 서버 enum Mission)

create table honey_worry (
    worry_id       bigint generated by default as identity primary key,
    member_id      bigint       not null references member (member_id),
    worry_text     varchar(500) not null,
    lang           varchar(20)  not null,
    is_anonymous   boolean      not null default true,
    show_tags      boolean      not null default false,
    status         varchar(20)  not null,
    hidden_at      timestamptz,
    hidden_reason  varchar(200),
    like_count     integer      not null default 0,
    answer_count   integer      not null default 0,
    created_at     timestamptz  not null,
    updated_at     timestamptz  not null
);
create index ix_honey_worry_waiting on honey_worry (status, answer_count, created_at);   -- 답을 기다리는 고민

create table honey_thought_tip (
    thought_tip_id    bigint generated by default as identity primary key,
    member_id         bigint       not null references member (member_id),
    worry_id          bigint       not null references honey_worry (worry_id),
    thought_tip_text  varchar(500) not null,
    lang              varchar(20)  not null,
    show_tags         boolean      not null default false,
    status            varchar(20)  not null,
    hidden_at         timestamptz,
    hidden_reason     varchar(200),
    like_count        integer      not null default 0,
    created_at        timestamptz  not null,
    updated_at        timestamptz  not null
);
create index ix_honey_thought_tip_list  on honey_thought_tip (status, created_at);   -- 생각꿀팁 목록
create index ix_honey_thought_tip_worry on honey_thought_tip (worry_id);             -- 고민 상세

create table honey_thought_tip_url (
    thought_tip_url_id  bigint generated by default as identity primary key,
    thought_tip_id      bigint       not null references honey_thought_tip (thought_tip_id),
    sort                integer      not null,
    url                 varchar(500) not null,
    created_at          timestamptz  not null
);
create index ix_honey_thought_tip_url_tip on honey_thought_tip_url (thought_tip_id);

create table honey_activity (
    activity_id    bigint generated by default as identity primary key,
    mission_no     integer,
    activity_key   varchar(100),
    is_default     boolean      not null default false,
    name           varchar(14),
    lang           varchar(20),
    description    text,
    created_by     bigint       references member (member_id),
    source         varchar(20)  not null,
    app_local_key  varchar(100),
    status         varchar(20)  not null,
    hidden_at      timestamptz,
    hidden_reason  varchar(200),
    use_count      integer      not null default 0,
    done_count     integer      not null default 0,
    like_count     integer      not null default 0,
    created_at     timestamptz  not null,
    updated_at     timestamptz  not null,
    constraint uk_honey_activity_mission_name unique (mission_no, name),
    constraint uk_honey_activity_app_local    unique (created_by, app_local_key)
);

create table honey_activity_url (
    activity_url_id  bigint generated by default as identity primary key,
    activity_id      bigint       not null references honey_activity (activity_id),
    sort             integer      not null,
    url              varchar(500) not null,
    created_at       timestamptz  not null
);
create index ix_honey_activity_url_activity on honey_activity_url (activity_id);

create table honey_activity_tip (
    activity_tip_id  bigint generated by default as identity primary key,
    worry_id         bigint      not null references honey_worry (worry_id),
    activity_id      bigint      not null references honey_activity (activity_id),
    member_id        bigint      not null references member (member_id),
    created_at       timestamptz not null,
    constraint uk_honey_activity_tip_worry_activity_member unique (worry_id, activity_id, member_id)
);

create table honey_schedule (
    schedule_id     bigint generated by default as identity primary key,
    member_id       bigint       not null references member (member_id),
    schedule_title  varchar(50)  not null,
    schedule_text   varchar(500),
    lang            varchar(20)  not null,
    show_tags       boolean      not null default false,
    status          varchar(20)  not null,
    hidden_at       timestamptz,
    hidden_reason   varchar(200),
    like_count      integer      not null default 0,
    send_count      integer      not null default 0,
    created_at      timestamptz  not null,
    updated_at      timestamptz  not null
);
create index ix_honey_schedule_list on honey_schedule (status, created_at);   -- 스케줄 목록

create table honey_schedule_activity (
    schedule_id  bigint      not null references honey_schedule (schedule_id),
    activity_id  bigint      not null references honey_activity (activity_id),
    days         varchar(20),
    created_at   timestamptz not null,
    updated_at   timestamptz not null,
    primary key (schedule_id, activity_id)
);
