-- 회원 · 닉네임 백업 · 약관 · 약관 동의 기록 (설계서 3절 4. 회원)
-- 시각은 모두 timestamptz (UTC)

create table member (
    member_id      bigint generated by default as identity primary key,
    provider       varchar(20)  not null,
    provider_uid   varchar(100),                      -- 탈퇴하면 비운다 (null)
    nickname       varchar(12),                       -- 탈퇴하면 비운다 (null)
    birth_year     integer,
    lang           varchar(20)  not null default 'ko',
    role           varchar(20)  not null,
    status         varchar(20)  not null default 'ACTIVE',   -- ACTIVE · WITHDRAWN
    withdrawn_at   timestamptz,
    last_login_at  timestamptz,
    created_at     timestamptz  not null,
    updated_at     timestamptz  not null,
    -- UQ 는 null 끼리 겹쳐도 된다 — 탈퇴한 회원은 null 이라, 같은 소셜 계정 · 닉네임으로 다시 가입할 수 있다
    constraint uk_member_provider_uid unique (provider, provider_uid),
    constraint uk_member_nickname     unique (nickname)
);

create table member_nickname_history (
    nickname_history_id  bigint generated by default as identity primary key,
    member_id            bigint      not null references member (member_id),
    nickname             varchar(12) not null,
    created_at           timestamptz not null
);
create index ix_member_nickname_history_member_created on member_nickname_history (member_id, created_at);

create table terms (
    terms_id      bigint generated by default as identity primary key,
    service       varchar(20) not null,
    type          varchar(20) not null,
    lang          varchar(20) not null,
    version       varchar(20) not null,
    body          text        not null,
    required      boolean     not null,
    effective_at  timestamptz not null,
    created_at    timestamptz not null,
    updated_at    timestamptz not null,
    constraint uk_terms_service_type_lang_version unique (service, type, lang, version)
);

create table member_terms_history (
    terms_history_id  bigint generated by default as identity primary key,
    member_id         bigint      not null references member (member_id),
    terms_id          bigint      not null references terms (terms_id),
    created_at        timestamptz not null,
    constraint uk_member_terms_history_member_terms unique (member_id, terms_id)
);
